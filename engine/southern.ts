// engine/southern.ts — **남반구 명식**: 土를 뺀 모든 글자를 충(沖)으로 바꾼다
// ═══════════════════════════════════════════════════════════════════════════
// ★★규칙은 **Boss 가 준 것**이다(2026-09-01). 받아적었을 뿐 내가 만든 것이 없다:
//     *"남반구는 토를 제외한 모든 글자를 충으로 바꾸면돼 만세력 등록할때"*
//     *"천간토는 안바꿔"*
//
// ■ 그래서 표는 이렇게만 된다 — **충 짝에서 土가 빠진 나머지 전부**
//     천간: 甲↔庚 · 乙↔辛 · 丙↔壬 · 丁↔癸        (戊己 = 土, 그대로)
//     지지: 子↔午 · 寅↔申 · 卯↔酉 · 巳↔亥        (丑辰未戌 = 土, 그대로)
//   ★확인해 보니 «土를 뺀 모든 충 짝» 과 정확히 일치한다 —
//     지지 여섯 짝(子午·丑未·寅申·卯酉·辰戌·巳亥) 중 丑未·辰戌이 土 쌍이라 저절로 빠진다.
//     즉 Boss 의 한 문장이 표 전체를 **빠짐없이** 정한다. 내가 보탤 자리가 없다.
//
// ■ ⚠️★**적용 범위는 원국 여덟 글자까지다**(Boss 문면: "만세력 등록할때").
//   대운·세운·월운까지 뒤집을지는 **정하지 않았다** — 그건 명리 판단이라 내가 정하지 않는다.
//   ⇒ `flipSaju` 는 원국만 건드리고, 운(運)은 그대로 둔다.
//     ★Boss 가 «운도 뒤집는다» 고 하면 그때 한 줄 늘리면 된다(구조는 이미 갈라 뒀다).
//
// ■ ⚠️판정 기준은 **위도 < 0** 하나다. 위도를 모르면 **안 뒤집는다** —
//   모르는 채로 뒤집는 것이 안 뒤집는 것보다 나쁘다(대부분은 북반구다).
// ═══════════════════════════════════════════════════════════════════════════

/** 천간 충 — ★戊己(土)는 **없다**(Boss: "천간토는 안바꿔"). */
export const CHUNG_STEM: Record<string, string> = {
  甲: '庚', 庚: '甲',
  乙: '辛', 辛: '乙',
  丙: '壬', 壬: '丙',
  丁: '癸', 癸: '丁',
};

/** 지지 충 — ★丑辰未戌(土)은 **없다**. */
export const CHUNG_BRANCH: Record<string, string> = {
  子: '午', 午: '子',
  寅: '申', 申: '寅',
  卯: '酉', 酉: '卯',
  巳: '亥', 亥: '巳',
};

/**
 * 남반구인가.
 * @param lat 출생지 위도(°N). 모르면 `undefined`
 * @returns 위도가 **음수일 때만** true. 모르면 false(안 뒤집는다)
 */
export function isSouthern(lat?: number | null): boolean {
  return typeof lat === 'number' && Number.isFinite(lat) && lat < 0;
}

/** 천간 한 글자를 뒤집는다. 土(戊己)와 모르는 글자는 **그대로**. */
export function flipStem(s: string): string { return CHUNG_STEM[s] ?? s; }

/** 지지 한 글자를 뒤집는다. 土(丑辰未戌)와 모르는 글자는 **그대로**. */
export function flipBranch(b: string): string { return CHUNG_BRANCH[b] ?? b; }

/** 간지 두 글자(예: `甲子`)를 뒤집는다. */
export function flipGz(gz: string): string {
  if (typeof gz !== 'string' || gz.length < 2) return gz;
  return flipStem(gz[0]) + flipBranch(gz[1]) + gz.slice(2);
}
