// app/src/lib/ui/avatarColor.ts — 사진 없는 사람의 **머리글자 원 색** (단일 원본)
// ═══════════════════════════════════════════════════════════════════════════
// Boss 2026-08-27: *"등록된 친구의 친구목록의 이미지랑 대화리스트의 이미지랑 다르게 나와"*
//
// ■ ★원인 — 색을 **목록 위치**로 정하고 있었다
//   친구목록은 `FALLBACK_EL[slot % 5]`, 대화목록은 `EL[(i + 1) % 5]`.
//   둘은 정렬이 다르므로 **같은 사람이 목록마다 다른 색**이 된다.
//   사진이 있으면 안 드러나지만, 사진이 없는 사람은 그 원이 곧 «그 사람의 얼굴» 이라
//   색이 바뀌면 **다른 사람처럼 보인다.**
//
// ■ ★고친 방식 — 색은 **사람에게 붙는다**
//   id 를 해시해 다섯 중 하나를 고른다. 목록이 어떻게 정렬되든 같은 사람은 같은 색이다.
//   ⚠️여기 한 곳에서만 정한다 — 두 목록이 각자 계산하면 언젠가 또 갈린다
//     ([[duplicate-ui-single-source]]).
//
// ■ ⚠️오행 색을 쓰지만 **명리 판정이 아니다**
//   실제 오행(일간)이 있으면 그걸 쓰는 쪽이 맞고, 이건 **없을 때의 자리 표시**다.
//   그래서 이름이 `fallback…` 이다 — 이 색에 뜻을 붙이면 안 된다.
// ═══════════════════════════════════════════════════════════════════════════

const EL = ['木', '火', '土', '金', '水'] as const;

/**
 * 사진이 없을 때 쓸 색(오행 다섯 중 하나).
 *
 * @param key 그 사람을 가리키는 **안정된 값**(사용자 id · 상담가 id). 비면 첫 색
 * @returns 오행 한 글자 — `elementColor[…]` 에 넣어 쓴다
 */
export function fallbackElement(key: string | null | undefined): (typeof EL)[number] {
  const k = (key ?? '').trim();
  if (!k) return EL[0];
  // ★djb2 계열의 짧은 해시 — 암호용이 아니라 **고르게 흩어지기만** 하면 된다
  let h = 5381;
  for (let i = 0; i < k.length; i++) h = ((h << 5) + h + k.charCodeAt(i)) | 0;
  return EL[Math.abs(h) % EL.length];
}
