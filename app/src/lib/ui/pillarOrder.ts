// ═══════════════════════════════════════════════════════════════════════════
// 왜 생겼나 (2026-08-16, daniel *"만세력 밴다이어그램에서 년주 월주 일주 시주 순으로 오른쪽부터 나오게"*)
//   같은 화면 안에서 명식이 **두 방향으로** 그려지고 있었다.
//     · 본 명식 그리드 : `POS = ['시','일','월','년']` 을 그대로 row 렌더 → 년주가 **오른쪽**(전통) ✅
//     · 벤다이어그램   : 같은 배열에 `.reverse()` → 년주가 **왼쪽** ❌
//   `LuckNest` 주석엔 *"전통 표기(오른쪽=년주)와 맞추기 위해 역순 렌더"* 라고 적혀 있었다.
//   의도는 맞았는데 **전제가 틀렸다** — 넘어오는 배열이 이미 전통 순서였다. 뒤집기가 한 번 더 걸린 것이다.
//
// ★교훈: 순서를 **배열 순서에 의존**하면, 호출부가 무슨 순서로 넘기는지에 따라 조용히 뒤집힌다.
//   그래서 여기서는 자리 이름(`년`·`월`·`일`·`시`)을 보고 **값으로** 정렬한다 — 넘어온 순서와 무관하게 같은 그림이 나온다.
//
// ⚠️이건 **표기 순서**지 계산 순서가 아니다. 엔진·판정 쪽(`sokgunghap`·`romanceMirror` 등)은
//   `['년','월','일','시']` 를 쓰는데 그건 자연스러운 시간 순서이고 화면과 무관하다 — 건드리지 말 것.
// ═══════════════════════════════════════════════════════════════════════════
import type { PillarPos } from '@spec/chart';

/**
 * 명식 표기 순서 — **왼 → 오 = 시·일·월·년**.
 * 곧 화면에서 **년주가 가장 오른쪽**이다(사주 명식의 전통 표기: 오른쪽에서 왼쪽으로 년월일시).
 */
export const PILLAR_DISPLAY_ORDER: PillarPos[] = ['시', '일', '월', '년'];

/**
 * 자리 이름의 표기 순위(왼쪽일수록 작다).
 *
 * @param pos `'년'`·`'년주'` 처럼 자리 글자로 **시작**하는 문자열(화면 라벨이 `'년주'` 형태라 접두 비교).
 * @returns 0~3. 모르는 값은 맨 뒤(배열에서 사라지지 않게 — 정렬은 자리만 바꾸지 버리지 않는다).
 */
export function pillarRank(pos: string): number {
  const i = PILLAR_DISPLAY_ORDER.findIndex((k) => pos.startsWith(k));
  return i < 0 ? PILLAR_DISPLAY_ORDER.length : i;
}

/**
 * 기둥 목록을 **화면 표기 순서로** 정렬한다(원본은 건드리지 않는다).
 *
 * @param items `pos` 를 가진 기둥들. 넘어온 순서가 무엇이든 상관없다 — 그게 이 함수의 존재 이유다.
 * @returns 왼→오 표기 순서(시·일·월·년)로 정렬된 **새 배열**
 *
 * @example
 * sortPillarsForDisplay([{pos:'년주'},{pos:'월주'},{pos:'일주'},{pos:'시주'}])
 * // → 시주 · 일주 · 월주 · 년주  (화면에서 년주가 오른쪽)
 */
export function sortPillarsForDisplay<T extends { pos: string }>(items: T[]): T[] {
  return [...items].sort((a, b) => pillarRank(a.pos) - pillarRank(b.pos));
}
