// app/src/lib/talk/splitBubbles.ts — 답 하나를 **대화하듯 짧은 말풍선들**로 쪼갠다
// ═══════════════════════════════════════════════════════════════════════════
// Boss 2026-08-25 *"일부 AI 선생님들은 자꾸 한번에 말을 길게 하는데 대화하듯이 짧게 끊어야해"*.
//
// ■ 왜 프롬프트로 안 되나
//   시스템 프롬프트에 «한 풍선은 짧은 한 문장» 을 이미 걸어 뒀는데도 어기는 상담가가 있다.
//   ⇒ **지시는 어겨도 글의 생김새는 못 어긴다.** 받은 글을 여기서 다시 쪼갠다.
//
// ■ 종전 쪼개기가 놓친 것 (2026-08-25 실측)
//   ①**빈 줄만** 봤다(`\n{2,}`) — 모델이 한 줄씩 띄어 쓰면(단일 `\n`) 한 덩어리로 남는다
//   ②**마침표만** 봤다(`[.!?]`) — 한국어 대화체는 «그럴 수 있죠» «많이 참았잖아요» 처럼
//     마침표 없이 끝나는 일이 잦다. 그러면 문장 열 개가 한 풍선이 된다
//   ③쪼갠 뒤에도 긴 조각을 **더 쪼개지 않았다** — 쉼표로 이어 붙인 만연체가 그대로 남는다
//
// ■ ⚠️너무 잘게 쪼개도 안 된다
//   «네.» «음.» 같은 두 글자 풍선이 줄줄이 뜨면 그것도 대화가 아니다.
//   ⇒ 짧은 조각은 **앞 풍선에 도로 붙인다**(`MIN_KEEP`).
// ═══════════════════════════════════════════════════════════════════════════

/**
 * 줄표(—·―·–)를 **우리말 문장부호로** 바꾼다.
 * ═══════════════════════════════════════════════════════════════════════
 * Boss 2026-08-27 *"대화 중간마다 「ㅡ」가 들어간다"*.
 *
 * ■ ★그 「ㅡ」의 정체 — **실측으로 갈랐다**
 *   한글 자모 「ㅡ」(U+3161)인 줄 알았는데, 저장된 답변 99건을 전수로 떠 보니
 *   U+3161 은 **0건**이고 **em dash(U+2014)가 7회·4건(답변의 8%)** 이었다.
 *   Pretendard 에서 em dash 는 「ㅡ」와 거의 같은 모양이라 그렇게 보인 것이다.
 *   ⇒ 실제로 Boss 가 마지막으로 본 대화(08-26 20:02)에 「…나누자고 하면 — 그때마다」가 있었다.
 *
 * ■ ⚠️지시로는 이미 두 번 실패했다
 *   서버 지문에 «줄표 금지: —, ―, – 를 쓰지 마라» 가 **적혀 있는데도** 8% 가 쓴다.
 *   `splitBubbles`·«당신» 지우기와 **같은 판단**이다 — 지시는 어겨도 글의 생김새는 못 어긴다.
 *
 * ■ 무엇을 어떻게 바꾸나
 *   ①숫자 사이는 **범위**다 → `2020—2024` → `2020~2024`
 *   ②문장 사이는 **쉼표**로 → `하면 — 그때마다` → `하면, 그때마다`
 *   ③문두·문말에 홀로 남은 것은 **지운다**(쉼표로 시작하는 문장은 없다)
 *   ④한글 자모 「ㅡ」도 같이 잡는다 — 모델이 금지를 **우회**해 이걸 쓸 수 있다.
 *     ⚠️단 「ㅡㅡ」처럼 **연달아** 오면 그건 표정이다. 건드리지 않는다.
 *
 * @param text 모델이 준 글
 * @returns 줄표가 우리말 부호로 바뀐 글
 */
export function plainDash(text: string): string {
  return String(text ?? '')
    // ①숫자 범위
    .replace(/(?<=\d)\s*[—―–]\s*(?=\d)/g, '~')
    // ③문두 — 줄 맨 앞에 남은 줄표(뒤 공백까지)
    .replace(/^[ \t]*[—―–][ \t]*/gm, '')
    // ③문말 — 줄 맨 끝
    .replace(/[ \t]*[—―–][ \t]*$/gm, '')
    // ★홀로 선 한글 자모 「ㅡ」 — 앞뒤가 「ㅡ」가 아닐 때만(「ㅡㅡ」는 표정이라 둔다)
    .replace(/(?<![ㅡ\S])ㅡ(?!ㅡ)(?=\s)/g, ',')
    // ②그 밖 — 쉼표로. 앞에 이미 부호가 있으면 부호를 겹치지 않는다
    .replace(/\s*[—―–]\s*/g, (_m, i, str) => (/[,.!?:;·]$/.test(str.slice(0, i)) ? ' ' : ', '))
    .replace(/ {2,}/g, ' ')
    .replace(/\s+([,.!?])/g, '$1');
}

/** 이 길이를 넘으면 더 쪼갠다. 한국어 한 문장이 보통 이 안에 들어온다. */
const SOFT_CAP = 52;
/** 여기를 넘으면 **쉼표에서라도** 끊는다. 카톡에서 60자는 이미 긴 편이다. */
const HARD_CAP = 60;
/** 이보다 짧은 조각은 앞 풍선에 도로 붙인다(«네.» 만 있는 풍선을 막는다). */
const MIN_KEEP = 6;

/** 문장 끝 — 문장부호 뒤. `…` 과 `~` 도 대화에서는 끝맺음이다. */
const BY_PUNCT = /(?<=[.!?…]|[.!?]["'」』])\s+/;
/**
 * 문장 끝 — **한국어 종결어미 뒤**. 마침표가 없어도 문장이 끝난 자리다.
 * ★뒤에 한글이 이어질 때만 쪼갠다 — «있죠?» 처럼 부호가 따라오면 위 규칙이 이미 잡는다.
 * ⚠️«~고», «~며» 같은 연결어미는 넣지 않는다. 문장이 안 끝났는데 끊긴다.
 *
 * ■ ★★2026-08-27 재설계 — Boss *"대화 줄바꿈 구간이 이상해"*
 *   종전은 `[요죠다까네]` 로 **끝 글자 하나만** 봤다. 저장된 답변 100건으로 실측하니
 *   이 규칙이 쪼갠 자리가 **9곳이었고 9곳 다 틀렸다**(이득 0 · 손해 9):
 *     「벌리는 것보다 ⏐ 굽는 게 먼저야」   ← '다' 는 비교조사였다
 *     「하면 — 그때마다 ⏐ 이 충이 울리는」  ← '다' 는 부사의 일부였다
 *     「사실 네 ⏐ 명식에서 제일 큰」        ← '네' 는 관형사(= 너의)였다
 *     「물으셨으니까 ⏐ 그것 중 하나를」     ← '까' 는 연결어미였다
 *     「피부 결감이 다 ⏐ 들어가니까」       ← '다' 는 «모두» 였다
 *   ⇒ 끝 글자 하나로는 «문장이 끝났는지» 를 알 수 없다. **어미 전체**를 본다.
 *
 * ■ 무엇을 남겼나 — 해요체 종결어미 **목록**
 *   `아요·어요·에요·예요·해요·세요·네요·데요·게요·래요·까요·나요·이요` + `죠`.
 *   ★이 목록은 오탐이 안 난다: 「중요」·「필요」·「인가요」는 앞 글자가 목록에 없어 안 걸린다.
 *   ⚠️물음표가 붙은 「인가요?」 는 **위 BY_PUNCT 가 이미 잡는다** — 여기서 또 볼 필요가 없다.
 *
 * ■ ⚠️반말 종결(~야·~어·~지·~해)은 **일부러 안 넣었다**
 *   「먹어 봐」·「해서 그래」처럼 연결어미와 생김새가 같아 오탐이 종전보다 더 난다.
 *   반말로 길어진 문장은 아래 ④ 쉼표 규칙이 맡는다. **실측 없이 규칙을 늘리지 않는다.**
 */
const BY_ENDING = /(?<=(?:[아어에예해세네데게래까나이]요|죠)[.!?]?)\s+(?=[가-힣"'(])/;

/**
 * 답 한 덩어리를 말풍선들로 쪼갠다.
 *
 * @param answer 모델이 준 답 전체
 * @returns 순서대로 띄울 말풍선 문자열들. 빈 답이면 빈 배열
 */
export function splitBubbles(answer: string): string[] {
  // ★쪼개기 **전에** 줄표를 우리말 부호로 바꾼다 — 서버가 이미 떼지만
  //   **이미 저장된 옛 대화**는 서버를 다시 거치지 않는다. 여기가 그 그물이다.
  const raw = plainDash(String(answer ?? '')).trim();
  if (!raw) return [];

  // ① 줄바꿈 — 빈 줄이든 한 줄이든 **모두** 경계로 본다
  let parts = raw.split(/\n+/).map((s) => s.trim()).filter(Boolean);

  // ② 긴 조각을 문장부호로
  parts = parts.flatMap((c) => (c.length <= SOFT_CAP ? [c] : c.split(BY_PUNCT)))
    .map((s) => s.trim()).filter(Boolean);

  // ③ 그래도 길면 한국어 종결어미로
  parts = parts.flatMap((c) => (c.length <= SOFT_CAP ? [c] : c.split(BY_ENDING)))
    .map((s) => s.trim()).filter(Boolean);

  // ④ 그래도 긴 만연체는 쉼표에서 끊는다(HARD_CAP 안쪽의 마지막 쉼표)
  //   ★쉼표가 없으면 **억지로 자르지 않는다** — 말 중간이 끊기면 대화가 아니라 고장으로 보인다
  parts = parts.flatMap((c) => {
    if (c.length <= HARD_CAP) return [c];
    const out: string[] = [];
    let rest = c;
    while (rest.length > HARD_CAP) {
      const cut = rest.lastIndexOf(', ', HARD_CAP);
      if (cut < MIN_KEEP) break;                 // 끊을 자리가 없으면 그냥 둔다(억지로 자르지 않는다)
      out.push(rest.slice(0, cut + 1).trim());
      rest = rest.slice(cut + 1).trim();
    }
    if (rest) out.push(rest);
    return out;
  });

  // ⑤ 너무 짧은 조각은 앞에 도로 붙인다
  const merged: string[] = [];
  for (const p of parts) {
    if (merged.length && p.length < MIN_KEEP) merged[merged.length - 1] += ` ${p}`;
    else merged.push(p);
  }

  // ⑥ ★`**강조**` 가 **두 풍선으로 갈리지 않게** 도로 붙인다 (2026-08-27 실측)
  //   실측된 자리: 「**양력인가요 ⏐ 음력인가요?**」 — 앞 풍선엔 여는 별표만, 뒤엔 닫는 별표만 남았다.
  //   `emph()` 는 **짝이 맞아야** 굵게 그린다 ⇒ 갈리면 양쪽 다 별표가 그대로 보인다.
  //   ★별표가 홀수인 풍선은 짝이 맞을 때까지 다음 풍선을 끌어온다.
  const bold: string[] = [];
  for (const p of merged) {
    const last = bold.length - 1;
    const odd = last >= 0 && (bold[last].split('**').length - 1) % 2 === 1;
    if (odd) bold[last] += ` ${p}`;
    else bold.push(p);
  }
  return bold.filter(Boolean);
}

/**
 * 이 말풍선을 치는 데 걸릴 «뜸» — 점 세 개가 보이는 시간(ms).
 *
 * ★Boss 2026-08-25 *"조금 긴문장은 …이 오래 표시 돼야하고 짧은건 좀 짧게"*.
 * ⚠️종전엔 **직전에 뜬 말**의 길이를 썼다 — 지금 치고 있는 말이 아니라 이미 읽은 말이었다.
 *   그래서 짧은 말 뒤에 긴 말이 와도 뜸이 짧았다.
 *
 * @param body 지금 **치고 있는**(곧 뜰) 말풍선
 */
export function typingDelay(body: string): number {
  const n = String(body ?? '').length;
  return Math.max(260, Math.min(2200, 260 + n * 16));
}
