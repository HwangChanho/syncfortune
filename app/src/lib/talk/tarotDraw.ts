// Boss 2026-09-01 기획 1~2단계: *"카드가 실제로 뽑히는 상담"* · 값은 **무료**
//
// ■ ⚠️★**모델이 뽑지 않는다.** 「카드를 뽑아라」 하면 매번 좋은 카드를 뽑는다 —
//   그럴듯한 이야기를 만들려 하기 때문이다. 우리가 뽑고, 모델은 **읽기만** 한다.
//
// ■ 뽑는 곳이 앱인 이유 — 덱(78장)이 `lib/tarot.ts` 에 있다.
//   Edge 로 옮기면 **사본이 둘**이 되어 카드 뜻이 화면과 대화에서 갈릴 수 있다.
//   ⇒ 규칙은 한 벌로 두고 **결과만** 보낸다.
//
// ■ ★기본은 **세 장**(Boss 기획 확정) — 10장은 카톡 호흡에 너무 길다.
// ■ ★값은 **무료**(Boss 2026-09-01) — 카드는 우리가 뽑으므로 추가 원가가 없다.
//   ⇒ 여기서 운을 세지 않는다. 그 턴의 보통 규칙만 적용된다.
// ═══════════════════════════════════════════════════════════════════════════
import { drawSpread } from '../tarot';
import { THREE, cardLine } from './tarotAsk';   // ★판정은 의존성 0 파일에(하네스가 진짜 함수를 돌린다)

export { THREE, wantsCards } from './tarotAsk';   // ★재수출 — 부르는 쪽은 한 곳만 알면 된다




/**
 * 세 장을 뽑아 **지문에 넣을 줄들**로 돌려준다.
 * @returns 카드 줄 3개. 이 배열이 그대로 서버로 가고, 답과 함께 저장된다
 */
export function drawThree(): string[] {
  return drawSpread(THREE).map((c: any) => cardLine(c.position, c.name, !!c.reversed));
}
