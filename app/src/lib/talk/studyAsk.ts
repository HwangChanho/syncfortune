/** 명리·자미 용어 — 이 낱말이 있어야 «공부» 후보가 된다. */
const TERMS = [
  '십신', '일간', '일주', '월지', '월령', '용신', '기신', '희신', '격국', '격',
  '대운', '세운', '월운', '신살', '공망', '지장간', '통근', '투출', '오행',
  '합', '충', '형', '해', '파', '십이운성', '십이신살', '조후', '억부', '병약',
  '천간', '지지', '음양', '만세력', '절기', '진태양시', '야자시', '신강', '신약',
  '자미두수', '명궁', '주성', '사화', '화록', '화권', '화과', '화기', '성반',
];

/** 「설명해 달라」 는 꼴. */
const ASK = [
  '뭐야', '뭐예요', '뭔가요', '무엇', '뭐지', '뭐임', '뭐에요',
  '뜻이', '뜻은', '의미', '개념', '차이', '다른점', '다른 점',
  '어떻게 보', '어떻게 잡', '어떻게 읽', '어떻게 계산', '어떻게 나오', '어떻게 정하',
  '원리', '왜 그렇', '설명', '알려줘', '가르쳐', '배우', '공부',
  '무슨 뜻', '란 무엇', '이란', '라는 게', '라는게',
];

/** 「내 것」 을 가리키는 말 — 이게 있으면 공부가 아니라 **자기 명식 질문**이다. */
const MINE = ['내 ', '내가', '나의', '제 ', '제가', '저의', '나는', '저는', '나도', '저도', '우리 애', '얘'];

/**
 * 이 물음이 **공부(개념 설명)** 인가.
 *
 * @param q 회원이 쓴 말
 * @returns 용어가 있고 · 설명을 청하고 · «내 것» 을 안 가리키면 true
 *
 * ★셋을 **모두** 만족해야 한다 — 하나라도 빠지면 false 다.
 *   느슨하게 잡으면 «내 사주 어때?» 까지 공부로 새어, 자기 풀이가 강의가 된다.
 */
export function isStudyAsk(q: string): boolean {
  const t = String(q ?? '');
  if (!t.trim()) return false;
  if (MINE.some((m) => t.includes(m))) return false;
  if (!TERMS.some((w) => t.includes(w))) return false;
  return ASK.some((a) => t.includes(a));
}

/** 물음에 들어 있는 용어들(지문에 그대로 실어 «무엇을 설명할지» 를 못 박는다). */
export function studyTerms(q: string): string[] {
  const t = String(q ?? '');
  return TERMS.filter((w) => t.includes(w));
}
