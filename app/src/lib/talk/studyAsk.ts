//   ②「십신이 뭐야?」 가 `isDeep()` 에 걸려 **골든 RAG 를 탄다** — 골든은 «특정 명식의 판정문» 이라
//     개념을 물었는데 **남(또는 내) 명식 판정**이 답으로 나온다. 그게 «이상한 소리» 다.
//   ③기본 지문이 *"차트에 정박"*(원칙 1) + *"★★한 턴에 한 가지만 · 3~4문장"* 이라
//     **개념 설명을 할 수가 없다.** 「십신이 뭐야」 에 내 십신 얘기를 3문장 하고 끝난다.
//
// ■ ★그래서 이 판정이 하는 일은 **«설명해 달라는 물음인가»** 뿐이다.
//   답을 어떻게 할지는 서버 지문이 정한다(여기는 재료를 만들지 않는다).
//
// ■ ⚠️★«내 것을 묻는 말» 과 갈라야 한다 — 이게 이 파일의 전부다
//   「내 십신 뭐야」 = 자기 명식 질문(종전대로) · 「십신이 뭐야」 = 공부.
//   둘을 같이 취급하면 공부를 열어 준 만큼 **자기 풀이가 교과서처럼 변한다.**
