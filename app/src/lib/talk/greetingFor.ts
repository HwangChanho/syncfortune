//   판정·풀이는 한 글자도 없다. **자기가 무엇을 보는 사람인지**를 자기 말투로 말할 뿐이다.
//   ⚠️말투의 결은 `consultant_examples`(Boss 검수본)와 **어긋나지 않게** 맞췄다 —
//     차언니는 반말, 유리는 짧게 끊기, 찐야는 친구처럼. 거기 적힌 것을 옮겨 온 것이다.
