// ═══════════════════════════════════════════════════════════════════════════
// Boss 2026-08-20: *"대화 할때 다양한 이미지들도 활용해서 보여주면 좋겠어"*
//
// ■ ★모델에게 고르게 하지 않는다
//   LLM 이 이미지 이름을 고르게 하면 ①없는 그림을 지어내고 ②프롬프트가 길어져 원가가 늘고
//   ③고를 때마다 달라져 같은 얘기에 다른 그림이 붙는다.
//   ⇒ **답변 텍스트에서 주제를 읽어 코드가 고른다.** 결정론이라 같은 얘기엔 같은 그림이고, 원가는 0이다.
//
// ■ ★그림은 아껴 쓴다
//   매 답변에 그림이 붙으면 대화가 아니라 카탈로그가 된다. 카톡에서 사람이 사진을 보내는 빈도를 생각하면
//   **한 대화에 한두 장**이 맞다. 그래서 ①주제가 뚜렷할 때만 ②같은 그림은 다시 안 쓴다.
//
// ■ 자산은 **이미 있는 것만** 쓴다(`brand/v3` 배너 일러스트 13장)
//   새 그림을 요청하지 않았다 — 있는 것으로 되는지부터 보는 게 순서다.
// ═══════════════════════════════════════════════════════════════════════════
import { bannerArt, type BannerArt } from '../ui/brandAsset';

/**
 * 주제 → 그림. **은유가 맞는 것만** 넣었다.
 * ★한 주제에 하나만 둔다 — 여러 후보를 두고 고르면 같은 얘기에 다른 그림이 붙는다.
 * ⚠️낱말이 아니라 **뜻**으로 묶는다. '돈'만 보면 "돈이 안 든다"에도 붙는다.
 */
const TOPICS: Array<{ art: BannerArt; re: RegExp }> = [
  // 인연·짝 — 둘이 나란한 그림
  { art: 'couple', re: /연애|인연|짝|배우자|결혼|사랑|고백|재회|썸/ },
  // 이동·이직·전환 — 문(다음 칸으로 넘어가는 자리)
  { art: 'door', re: /이직|이사|옮기|퇴사|전직|바꾸는|바뀌는|전환|떠나/ },
  // 시작·기회 — 해가 뜨는 그림
  { art: 'sunrise', re: /시작|출발|기회|열리|새로운 일|도전/ },
  // 선택·방향 — 나침반
  { art: 'compass', re: /선택|결정|어느 쪽|방향|고민 중|갈림/ },
  // 쌓아 올리기·승진 — 계단
  { art: 'stairs', re: /승진|올라|단계|성장하|자격증|경력|실력을? 쌓/ },
  // 재물·모으기 — 네잎클로버(행운)보다 나무(뿌리내려 크는 것)가 재물에 맞다
  { art: 'tree', re: /재물|돈이|자산|모으|저축|투자(?!조언)|수입/ },
  // 변화·달라짐 — 나비
  { art: 'butterfly', re: /변화|달라지|거듭나|바꾸고 싶|새 사람/ },
  // 마음·쉼·회복 — 촛불
  { art: 'candle', re: /지치|힘들|우울|불안|쉬어|마음이|버티/ },
  // 관계·가족 — 숲(여럿이 어울린 그림)
  { art: 'forest', re: /가족|부모|자녀|형제|동료|사람들과|관계가/ },
  // 공부·기록 — 펜
  { art: 'pen', re: /공부|시험|자격|글을|기록|배우/ },
  // 운·행운 — 클로버
  { art: 'clover', re: /운이|행운|복이|길하/ },
  // 기다림·잠잠함 — 달빛 호수
  { art: 'moonlake', re: /기다|잠잠|조용|참고|때를/ },
];

/**
 * 이 답변에 붙일 그림을 고른다.
 *
 * @param text  상담사 답변(또는 사용자 질문 — 주제가 더 뚜렷한 쪽을 넘겨도 된다)
 * @param used  이 대화에서 **이미 쓴** 그림들(같은 그림을 반복하지 않는다)
 * @returns 그림 소스와 이름. 주제가 뚜렷하지 않으면 null(그림을 안 붙인다)
 *
 * ★null 을 자주 돌려주는 것이 정상이다 — 그림은 있으면 좋은 것이지 매번 있어야 하는 게 아니다.
 */
export function pickTalkImage(
  text: string,
  used: ReadonlySet<string>,
): { art: BannerArt; source: ReturnType<typeof bannerArt> } | null {
  if (!text || text.length < 20) return null;      // 너무 짧은 답에 그림을 붙이면 그림이 본문이 된다
  for (const t of TOPICS) {
    if (used.has(t.art)) continue;                 // 같은 그림 반복 금지
    if (t.re.test(text)) return { art: t.art, source: bannerArt(t.art) };
  }
  return null;
}
