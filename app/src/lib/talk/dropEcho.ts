// app/src/lib/talk/dropEcho.ts — 사용자의 **짧은 대꾸를 그대로 되뇌는 첫 줄**을 떼어 낸다
// ═══════════════════════════════════════════════════════════════════════════
// ★Boss 2026-09-02: *"어 하면 왜 어 따라하는거야"*
//   실제 화면: 사용자가 「어」 → 노쌤이 「어.」 「네, 알았어요.」 … 로 시작했다.
//
// ■ 왜 이런 말이 나오나 — 지시문에 *"★먼저 반응하고 그다음 알려 준다"* 가 있다
//   (예: "아 그거 진짜 속상하죠."). 그런데 「어」 처럼 **내용이 없는 대꾸**에는 반응할 것이 없어,
//   모델이 그 말을 **그대로 되받는다**. 사람은 그렇게 말하지 않는다 — 앵무새로 들린다.
//   ★같은 자리에서 08-31 에도 사고가 있었다(「어」에 「편하게 말씀해도 괜찮아요」로 답한 것).
//
// ■ ⚠️★지시문만 고치지 않는다. 지시문은 «대체로» 지켜질 뿐이라 또 샌다
//   (이 저장소의 교훈: 지시문 검사 ≠ 산출물 검사). 그래서 **산출물에서 실제로 뗀다.**
//
// ■ 무엇을 떼나 — **첫 조각이 사용자의 말과 같을 때만.** 그 외에는 손대지 않는다.
//   · 「어」 → 「어.」 「어…」 「어!」  ⇒ 뗀다
//   · 「응」 → 「응.」                ⇒ 뗀다
//   · 「어」 → 「어제 말씀하신 건」    ⇒ **안 뗀다**(다른 말이다)
//   · 「배고파」 → 「배고파.」         ⇒ **안 뗀다**(짧은 대꾸가 아니라 내용이 있는 말)
//   ⇒ 조건이 셋 다 맞아야 뗀다: ①사용자 말이 **내용 없는 대꾸**이고
//     ②답의 **첫 조각**이 그 말과 같고 ③떼고도 **남는 말이 있다**.
//
// ★이 파일은 **의존 0**이다(순수 문자열 함수). 하네스가 앱·Edge 없이 그대로 부른다.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * 내용이 없는 짧은 대꾸들 — 「알겠다·응답했다」 외에 정보가 없는 말.
 * ★여기 있는 말에만 규칙이 걸린다. 넓히면 멀쩡한 답의 첫 줄을 지운다.
 */
const FILLERS = [
  '어', '응', '음', '아', '오', '엉', '웅',
  'ㅇ', 'ㅇㅇ', 'ㅇㅋ', 'ㄱㄱ', 'ㅎㅇ',
  '네', '넵', '넹', '예', '옙', '그래', '그랭', '오케이', '오키', 'ok', 'okay',
];

/** 문장 끝의 마침표·물결·느낌표·물음표·말줄임과 공백을 걷어낸 **비교용** 형태. */
function bare(s: string): string {
  return s.trim().replace(/[.。!！?？~〜…\s]+$/u, '').trim().toLowerCase();
}

/** 사용자의 말이 **내용 없는 짧은 대꾸**인가. */
export function isFiller(userText: string): boolean {
  const b = bare(userText);
  if (!b || b.length > 4) return false;          // 네 글자를 넘으면 내용이 있다고 본다
  return FILLERS.includes(b);
}

/**
 * 답의 **첫 조각이 사용자의 말을 그대로 되뇌면** 그 조각을 뗀다.
 *
 * @param answer   모델이 낸 답 전체(여러 줄일 수 있다)
 * @param userText 직전에 사용자가 보낸 말
 * @returns        되뇐 첫 조각을 뗀 답. 뗄 것이 없으면 **원문 그대로**.
 *
 * ⚠️떼고 나서 **남는 말이 없으면 안 뗀다** — 빈 답을 내보내는 것이 되뇌는 것보다 나쁘다.
 * ⚠️첫 조각만 본다. 답 중간에 같은 말이 나오는 것은 문맥일 수 있어 건드리지 않는다.
 */
export function dropEcho(answer: string, userText: string): string {
  if (!answer || !isFiller(userText)) return answer;
  const want = bare(userText);
  const lines = answer.split('\n');
  // 첫 **비어 있지 않은** 줄을 찾는다(앞에 빈 줄이 있을 수 있다)
  let i = 0;
  while (i < lines.length && !lines[i].trim()) i++;
  if (i >= lines.length) return answer;

  // 그 줄 전체가 되뇌기인가 / 줄 안 첫 문장만 되뇌기인가
  const line = lines[i];
  if (bare(line) === want) {
    const rest = lines.slice(i + 1).join('\n').trim();
    return rest ? rest : answer;                 // 남는 말이 없으면 그대로 둔다
  }
  // 「어. 네, 알았어요.」 처럼 한 줄 안에 붙어 있는 경우 — 첫 문장만 잘라 본다
  const m = line.match(/^\s*([^.!?。！？]{1,4})[.!?。！？]+\s*(.*)$/u);
  if (m && bare(m[1]) === want && m[2].trim()) {
    lines[i] = m[2].trim();
    return lines.join('\n').trim();
  }
  return answer;
}
