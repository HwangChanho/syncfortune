/**
 * 코치 답변 아래에 붙일 콘텐츠 안내를 고른다.
 * @param question 사용자가 실제로 쓴 질문(★여기 나온 말로만 판단 — 선제 제안 금지)
 * @param owned    이미 보유한 콘텐츠 키 집합(`ownedKeysFrom` 산출물)
 * @param exclude  지금 보고 있는 화면 등 제외할 키
 * @returns 안내 1건 또는 null
 */
export function pickCoachRoute(question: string, owned: Set<string>, exclude?: string): CoachRoute | null {
  const q = (question ?? '').replace(/\s+/g, ' ');
  if (!q.trim()) return null;
  for (const r of RULES) {
    if (r.key === exclude) continue;
    if (r.words.some((w) => q.includes(w))) {
      return { key: r.key, reason: r.reason, owned: owned.has(r.key) };
    }
  }
  return null;   // ★안 걸리면 아무것도 안 붙인다. 매번 뜨면 광고로 읽힌다.
}

/** 하네스·검증용 — 라우팅이 가리키는 콘텐츠 키 전부. */
export function routeKeys(): string[] {
  return RULES.map((r) => r.key);
}
