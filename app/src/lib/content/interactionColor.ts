//     ① 흰 카드 위 대비 **4.8 이상**(본문 기준 4.5 + 여유)
//     ② 서로 RGB 거리 **77 이상**(종전 배색은 최악 49 였다 — 형↔해가 사실상 같은 색)
//     ③ **오행색과 55 이상** 떨어질 것 — 같은 행에 오행색 글자가 함께 있어서,
//        작용 색이 오행색과 비슷하면 «이 글자가 木이라 초록인가, 합이라 초록인가» 가 섞인다
//   밝기는 30~45% 로 좁혔다. 전부 «중간 어두움» 이고 **갈리는 축은 색상(hue)** 이다 —
//   사람은 어두운 두 색을 명도로 구분하지 못한다.
//
// ■ ⚠️강조 테두리는 이 색을 **그대로 쓰면 안 된다**
//   오행 칸 배경(木#3E8E5A · 火#C0392B · 土#C9A14A · 金#D2CCBA · 水#3A4E7A) 위에서
//   이 색들의 대비는 **1.06~1.10** 이다 — 3px 테두리를 둘러도 **안 보인다**.
//   ⇒ 화면은 **흰 고리(ring)를 한 겹 끼워** 색 테두리를 배경에서 떼어 놓는다(`INTERACTION_RING`).
//      배경이 밝든 어둡든 흰 틈이 있어 색이 살아난다.
// ═══════════════════════════════════════════════════════════════════════════

/** 두 글자 사이에서 일어나는 작용. `detectInteractionsAmong` 가 내는 `type` 과 같아야 한다. */
export type InteractionType = '합' | '충' | '형' | '해' | '파' | '극';

/** 표시 순서 — 화면이 이 순서로 묶어서 보여 준다(강한 것부터가 아니라 **익숙한 순서**). */
export const INTERACTION_ORDER: InteractionType[] = ['합', '충', '형', '해', '파', '극'];

/**
 * 작용별 색. ★위 세 조건을 만족하도록 **계산해서** 고른 값이다 — 바꾸려면 다시 재라.
 * `check:interactioncolor` 가 조건을 지킨다.
 */
export const INTERACTION_COLOR: Record<InteractionType, string> = {
  합: '#198033',   // 초록 135° — 어울림
  충: '#8F1919',   // 적 0°     — 정면 부딪힘
  형: '#8B6A3C',   // 청동 35°  — 마찰·구설
  해: '#951D71',   // 자두 318° — 방해·시기
  파: '#1A7793',   // 청 194°   — 깨짐·중단
  극: '#4822C3',   // 보라 254° — 누름
};

/** 강조 고리에 끼우는 색 — 색 테두리를 오행 배경에서 떼어 놓는 틈. */
export const INTERACTION_RING = '#FFFFFF';

/**
 * 작용 색을 준다.
 * @param ty 작용 종류. 모르는 값이면 먹색 계열로 떨어진다(화면이 비지 않게)
 */
export function interactionColor(ty: string): string {
  return INTERACTION_COLOR[ty as InteractionType] ?? '#5A5048';
}
