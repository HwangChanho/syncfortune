// ─────────────────────────────────────────────────────────────────────────
// daniel 2026-08-11: *"만세력 시간 입력 오전오후 나누지말고 입력하는사람이 24시간 기준으로 입력하게 하자"*
//
// ■ 왜 오전/오후를 없앴나 (이력)
//   · 07-17 daniel: 24시간제만 있어 `12:30` 이 낮/밤 헷갈린다 → **오전/오후 토글**을 넣었다.
//   · 08-11 daniel 제보: **`00:03` 이 등록이 안 됐다.** 원인은 12시간제라 시가 `1~12` 뿐이었던 것.
//     사람들은 자정을 `00:03` 으로 친다. 토글을 두면 *"밤 12시가 오전인가 오후인가"* 를 또 묻게 된다.
//   ⇒ 저장 형식이 어차피 **24시간제**이므로, 입력도 24시간제로 받는 것이 변환 자체를 없앤다.
//     `00`=자정 · `12`=정오 · `23`=밤 11시 — 헷갈릴 자리가 사라진다.
//
// ■ ★규칙을 화면 안에 두지 않는 이유
//   화면에만 있으면 골든이 **복사본**을 검사하게 된다(실제로 그랬다 — 화면을 되돌려도 통과했다).
//   화면과 골든이 **같은 함수**를 쓰도록 여기 둔다. RN 의존이 없어 헤드리스 실행도 된다.
// ─────────────────────────────────────────────────────────────────────────

export type BirthTimeParse = {
  /** 24시간제 문자열 `H:mm`. 유효하지 않으면 null. */
  h24: string | null;
  /** 시(0~23). 유효하지 않으면 NaN. */
  hour: number;
  /** 분(0~59). 유효하지 않으면 NaN. */
  minute: number;
  /** 확인이 안 되는 이유(사람 말). 유효하면 null. ★침묵하지 않기 위한 필드다. */
  why: string | null;
};

/**
 * 태어난 시각 입력(24시간제)을 검증하고 저장 형식으로 만든다.
 *
 * @param hStr 시 입력(문자열 그대로 — 빈 칸과 `0` 을 가르기 위해)
 * @param mStr 분 입력
 * @returns `h24`(저장·계산용) · 시/분 · 막힌 이유
 *
 * @example
 *   parseBirthTime('00', '03').h24   // '0:03'  ← 자정 3분(daniel 신고 건)
 *   parseBirthTime('23', '59').h24   // '23:59'
 *   parseBirthTime('24', '00').why   // '시(時)는 0~23 이어야 해요: 24'
 */
export function parseBirthTime(hStr: string, mStr: string): BirthTimeParse {
  const h = parseInt(hStr, 10), m = parseInt(mStr, 10);

  const why = (hStr === '' && mStr === '') ? null
    : hStr === '' ? '시(時)를 입력해 주세요.'
    : mStr === '' ? '분(分)을 입력해 주세요.'
    : !(h >= 0 && h <= 23) ? `시(時)는 0~23 이어야 해요: ${hStr}`
    : !(m >= 0 && m <= 59) ? `분(分)은 0~59 여야 해요: ${mStr}`
    : null;

  const valid = hStr !== '' && mStr !== '' && h >= 0 && h <= 23 && m >= 0 && m <= 59;
  return {
    h24: valid ? `${h}:${String(m).padStart(2, '0')}` : null,
    hour: valid ? h : NaN,
    minute: valid ? m : NaN,
    why,
  };
}

/**
 * 24시간제 시각을 사람이 읽기 좋게 — 헷갈리는 자리만 꼬리표를 붙인다.
 * @example  hourHint(0) // '자정'  ·  hourHint(12) // '정오'  ·  hourHint(9) // null
 * ★`0`·`12` 만 붙인다. 나머지는 24시간제 그대로가 더 명확하다(꼬리표가 많으면 오히려 읽기 어렵다).
 */
export function hourHint(hour: number): string | null {
  return hour === 0 ? '자정' : hour === 12 ? '정오' : null;
}
