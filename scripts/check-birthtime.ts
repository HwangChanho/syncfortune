// scripts/check-birthtime.ts — 명식 등록의 **시각 입력**이 사람이 치는 대로 받아지는가
// ═══════════════════════════════════════════════════════════════════════════
// daniel 2026-08-11: *"만세력에 00:03 출생은 등록이 안되는데?"*
//
// 원인(실측): 입력은 **12시간제**(오전/오후 + 1~12)인데 `exactValid` 가 `1~12` 만 받았다.
//   자정 3분을 사람들은 **`00:03`**(24h 습관)이라고 친다 → `exH12=0` → 유효성 실패 →
//   **확인 버튼이 잠기고, 왜 안 되는지는 아무 데도 안 떴다.** `13~23` 도 같은 이유로 막혀 있었다.
//
// ★이 하네스는 화면을 렌더하지 않고 **변환 규칙만** 검사한다(화면 로직과 같은 식을 여기 옮겨 둔다).
//   그래서 값이 갈리면 안 된다 — 아래 `to24` 는 ChartRegisterScreen 의 식과 **한 글자도 다르지 않아야** 한다.
//   ⚠️화면 쪽을 고치면 여기도 같이 고칠 것(둘 다 안 고치면 이 검사가 통과하면서 화면만 틀린다).
// 실행: npm run check:birthtime
// ═══════════════════════════════════════════════════════════════════════════
import fs from 'fs';
import { parseBirthTime } from '../app/src/lib/engine/birthTime';

let pass = 0, fail = 0;
const check = (name: string, cond: boolean, detail = '') => {
  if (cond) { pass++; console.log(`  ✓ ${name}`); } else { fail++; console.log(`  ✗ ${name}  ${detail}`); }
};

/** ★화면과 **같은 함수**를 검사한다 — 복사본이 아니다(그래서 화면만 고쳐도 여기가 문다). */
const to24 = (h: string, m: string, ampm: '오전' | '오후') => parseBirthTime(h, m, ampm).h24;

console.log('\n🕐 명식 등록 — 태어난 시각 입력\n');

// ── ① daniel 이 신고한 그 입력 ────────────────────────────────────────────
check('★00:03 이 등록된다 → 0:03 (daniel 신고 건)', to24('00', '03', '오후') === '0:03', String(to24('00', '03', '오후')));
check('00:03 은 오전/오후 토글과 무관하게 자정이다', to24('00', '03', '오전') === '0:03' && to24('00', '03', '오후') === '0:03');

// ── ② 24시간제로 친 값 흡수 ───────────────────────────────────────────────
check('13:30 → 13:30 (오후 1시 반)', to24('13', '30', '오전') === '13:30', String(to24('13', '30', '오전')));
check('23:59 → 23:59', to24('23', '59', '오전') === '23:59', String(to24('23', '59', '오전')));
check('0:00 → 0:00 (자정 정각)', to24('0', '00', '오후') === '0:00', String(to24('0', '00', '오후')));

// ── ③ 12시간제 본래 동작이 안 깨졌는가 (대조군) ───────────────────────────
check('대조군: 오전 12:03 = 자정', to24('12', '03', '오전') === '0:03', String(to24('12', '03', '오전')));
check('대조군: 오후 12:03 = 정오', to24('12', '03', '오후') === '12:03', String(to24('12', '03', '오후')));
check('대조군: 오전 7:10 = 7:10', to24('7', '10', '오전') === '7:10', String(to24('7', '10', '오전')));
check('대조군: 오후 7:10 = 19:10', to24('7', '10', '오후') === '19:10', String(to24('7', '10', '오후')));

// ── ④ 진짜 잘못된 입력은 여전히 막는가 (음성) ─────────────────────────────
check('음성: 24 시는 막힌다', to24('24', '00', '오전') === null);
check('음성: 분 60 은 막힌다', to24('5', '60', '오전') === null);
check('음성: 빈 칸은 막힌다', to24('', '30', '오전') === null && to24('5', '', '오전') === null);

// ── ⑤ 화면이 **같은 함수**를 쓰는가 · 침묵하지 않는가 ─────────────────────
//   ①~④ 는 이미 화면과 같은 `parseBirthTime` 을 검사한다(복사본이 아니다).
//   여기서는 화면이 그 함수를 실제로 **쓰고 있고**, 막힐 때 이유를 표시하는지만 본다.
{
  const src = fs.readFileSync('app/src/screens/ChartRegisterScreen.tsx', 'utf8');
  check('화면이 parseBirthTime 을 쓴다(식을 다시 적지 않았다)',
    /parseBirthTime\(/.test(src) && !/rawH >= 13 && rawH <= 23/.test(src));
  check('★확인이 막힐 때 **이유를 보여 준다**(침묵 금지)', /exactWhy/.test(src));
  check('★24h 로 읽었음을 알려 준다', /h24Read/.test(src));
}

// ── ⑥ 부가 출력 — 화면이 쓰는 나머지 필드도 값이 맞는가 ────────────────────
{
  const a = parseBirthTime('00', '03', '오후');
  check('00 은 24h 표기로 인식된다(typed24h)', a.typed24h === true);
  check('00 의 적용 오전/오후는 오전이다', a.ampm === '오전');
  check('00 의 표시 시는 12 다(오전 12:03)', a.h12 === 12);
  check('막힌 이유가 문장으로 나온다', (parseBirthTime('24', '00', '오전').why ?? '').includes('1~12'));
  check('대조군: 유효하면 이유가 없다', parseBirthTime('7', '10', '오전').why === null);
}

console.log(`\n태어난 시각 입력  PASS ${pass} / FAIL ${fail}`);
if (fail) process.exitCode = 1;
